//! Translates `schema/notability-ops.fbs` with planus and emits `schema_desc.rs` into `OUT_DIR`:
//! a static descriptor that drives the forward-layout codec in `codec.rs`. The codec must match
//! the reference encodings byte for byte (so planus' back-to-front builder is not used) and must
//! tolerate vtables that planus' readers reject (a union tag slot without its value slot).

use std::fmt::Write as _;
use std::path::PathBuf;

use planus_types::ast::{FloatType, IntegerType};
use planus_types::intermediate::{
    Declaration, DeclarationKind, Declarations, SimpleType, TypeKind,
};

const SCHEMA: &str = "schema/notability-ops.fbs";

fn main() {
    println!("cargo::rerun-if-changed={SCHEMA}");
    println!("cargo::rerun-if-changed=build.rs");
    let decls = planus_translation::translate_files(&[SCHEMA])
        .unwrap_or_else(|| panic!("planus could not translate {SCHEMA}"));
    let out = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out.join("schema_desc.rs"), descriptor(&decls)).expect("write schema_desc.rs");
}

fn name(decls: &Declarations, idx: usize) -> String {
    let (path, _) = decls.get_declaration(planus_types::intermediate::DeclarationIndex(idx));
    path.0.last().cloned().unwrap_or_default()
}

fn decl(decls: &Declarations, idx: usize) -> &Declaration {
    decls
        .get_declaration(planus_types::intermediate::DeclarationIndex(idx))
        .1
}

fn scalar(t: &SimpleType, decls: &Declarations) -> Option<&'static str> {
    Some(match t {
        SimpleType::Bool => "Bool",
        SimpleType::Integer(i) => int(*i),
        SimpleType::Float(FloatType::F32) => "F32",
        SimpleType::Float(FloatType::F64) => "F64",
        SimpleType::Enum(e) => match &decl(decls, e.0).kind {
            DeclarationKind::Enum(en) => int(en.type_),
            _ => unreachable!("enum index points at a non-enum"),
        },
        SimpleType::Struct(_) => return None,
    })
}

fn int(i: IntegerType) -> &'static str {
    match i {
        IntegerType::U8 => "U8",
        IntegerType::U16 => "U16",
        IntegerType::U32 => "U32",
        IntegerType::U64 => "U64",
        IntegerType::I8 => "I8",
        IntegerType::I16 => "I16",
        IntegerType::I32 => "I32",
        IntegerType::I64 => "I64",
    }
}

/// Index of a declaration among declarations of the same kind (the descriptor's arrays).
struct Index {
    tables: Vec<usize>,
    structs: Vec<usize>,
    unions: Vec<usize>,
}

impl Index {
    fn pos(list: &[usize], d: usize) -> usize {
        list.iter()
            .position(|&x| x == d)
            .expect("declaration indexed")
    }
}

fn simple(t: &SimpleType, decls: &Declarations, ix: &Index) -> String {
    match t {
        SimpleType::Struct(s) => format!("Ty::Struct({})", Index::pos(&ix.structs, s.0)),
        other => format!("Ty::Scalar(Sc::{})", scalar(other, decls).expect("scalar")),
    }
}

fn ty(t: &TypeKind, decls: &Declarations, ix: &Index) -> String {
    match t {
        TypeKind::SimpleType(s) => simple(s, decls, ix),
        TypeKind::String => "Ty::String".into(),
        TypeKind::Table(d) => format!("Ty::Table({})", Index::pos(&ix.tables, d.0)),
        TypeKind::Union(d) => format!("Ty::Union({})", Index::pos(&ix.unions, d.0)),
        TypeKind::Vector(inner) => {
            let e = match &inner.kind {
                TypeKind::SimpleType(s) => match s {
                    SimpleType::Struct(x) => {
                        format!("El::Struct({})", Index::pos(&ix.structs, x.0))
                    }
                    other => format!("El::Scalar(Sc::{})", scalar(other, decls).expect("scalar")),
                },
                TypeKind::String => "El::String".into(),
                TypeKind::Table(d) => format!("El::Table({})", Index::pos(&ix.tables, d.0)),
                k => panic!("unsupported vector element {k:?}"),
            };
            format!("Ty::Vector({e})")
        }
        TypeKind::Array(..) => panic!("arrays are not used by the wire schema"),
    }
}

fn descriptor(decls: &Declarations) -> String {
    let mut ix = Index {
        tables: vec![],
        structs: vec![],
        unions: vec![],
    };
    for (i, d) in decls.declarations.values().enumerate() {
        match d.kind {
            DeclarationKind::Table(_) => ix.tables.push(i),
            DeclarationKind::Struct(_) => ix.structs.push(i),
            DeclarationKind::Union(_) => ix.unions.push(i),
            _ => {}
        }
    }
    let mut s = String::from("// @generated by build.rs from schema/notability-ops.fbs\n\n");
    s.push_str("pub static STRUCTS: &[StructDef] = &[\n");
    for &d in &ix.structs {
        let DeclarationKind::Struct(st) = &decl(decls, d).kind else {
            unreachable!()
        };
        let _ = write!(
            s,
            "    StructDef {{ name: {:?}, size: {}, align: {}, fields: &[",
            name(decls, d),
            st.size,
            st.alignment
        );
        for (fname, f) in &st.fields {
            let _ = write!(
                s,
                "SField {{ name: {fname:?}, ty: {}, offset: {} }}, ",
                simple(&f.type_, decls, &ix),
                f.offset
            );
        }
        s.push_str("] },\n");
    }
    s.push_str("];\n\npub static TABLES: &[TableDef] = &[\n");
    for &d in &ix.tables {
        let DeclarationKind::Table(t) = &decl(decls, d).kind else {
            unreachable!()
        };
        let _ = write!(s, "    TableDef {{ name: {:?}, fields: &[", name(decls, d));
        for (fname, f) in &t.fields {
            if f.deprecated {
                continue;
            }
            if let TypeKind::Union(_) = f.type_.kind {
                // The implied tag field `<name>Type` (u8) sits at the preceding slot.
                let _ = write!(
                    s,
                    "TField {{ name: \"{fname}Type\", slot: {}, ty: Ty::Scalar(Sc::U8) }}, ",
                    f.vtable_index
                );
                let _ = write!(
                    s,
                    "TField {{ name: {fname:?}, slot: {}, ty: {} }}, ",
                    f.vtable_index + 1,
                    ty(&f.type_.kind, decls, &ix)
                );
            } else {
                let _ = write!(
                    s,
                    "TField {{ name: {fname:?}, slot: {}, ty: {} }}, ",
                    f.vtable_index,
                    ty(&f.type_.kind, decls, &ix)
                );
            }
        }
        s.push_str("] },\n");
    }
    s.push_str("];\n\npub static UNIONS: &[UnionDef] = &[\n");
    for &d in &ix.unions {
        let DeclarationKind::Union(u) = &decl(decls, d).kind else {
            unreachable!()
        };
        let _ = write!(
            s,
            "    UnionDef {{ name: {:?}, variants: &[",
            name(decls, d)
        );
        for (vname, v) in &u.variants {
            let target = match &v.type_.kind {
                TypeKind::Table(t) => format!("Variant::Table({})", Index::pos(&ix.tables, t.0)),
                TypeKind::SimpleType(SimpleType::Struct(x)) => {
                    format!("Variant::Struct({})", Index::pos(&ix.structs, x.0))
                }
                k => panic!("unsupported union variant {vname}: {k:?}"),
            };
            let _ = write!(s, "({vname:?}, {target}), ");
        }
        s.push_str("] },\n");
    }
    s.push_str("];\n");
    s
}
